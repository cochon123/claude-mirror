// Builds timing.ts for the Remotion composition from the narration durations.
import { readFileSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { join } from 'node:path';
// the Remotion project that renders the videos lives outside this repo
const REMOTION = process.env.REMOTION_DIR || join(homedir(), 'video/remotion');
// TIMING_SET=results builds results-timing.ts for the results video.
const RES = process.env.TIMING_SET === 'results';
const VO = join(REMOTION, 'public/videos/claude-mirror-room', RES ? 'vo-results' : 'vo', 'lines.json');
const OUT = join(REMOTION, 'src/videos/claude-mirror-room', `${RES ? 'results-timing' : 'timing'}.ts`);
const fps = 30, LEAD = 12, TAIL = 20;
const meta = JSON.parse(readFileSync(VO, 'utf8'));
let from = 0;
// scene order on screen (s9, the open room, was added later and plays before the outro)
const ORDER = RES ? ['r1', 'r2', 'r3', 'r4', 'r5', 'r6', 'r7', 'r9', 'r8'] : ['s1', 's2', 's3', 's4', 's5', 's6', 's7', 's9', 's8'];
const scenes = ORDER.filter((id) => meta[id]).map((id) => {
  const voiceFrames = Math.ceil(meta[id].dur * fps);
  const s = { id, from, duration: LEAD + voiceFrames + TAIL + (id === 's8' || id === 'r8' ? 45 : 0), voiceFrames, text: meta[id].text };
  from += s.duration;
  return s;
});
writeFileSync(OUT, `// generated by claude-mirror/video/timing.mjs\nexport const LEAD = ${LEAD};\nexport const timeline = ${JSON.stringify({ fps, totalFrames: from, scenes }, null, 1)};\n`);
console.log('total frames', from, (from / fps).toFixed(1) + 's');
